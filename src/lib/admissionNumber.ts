/**
 * Automatic & Manual Student Admission Number utilities for Divine Academy Portal.
 *
 * Preserves the existing school format: `STD/<YEAR>/<NNNN>` (e.g. `STD/2026/0001`).
 * Guarantees:
 *  - Leaving the Admission Number empty automatically generates the next unique number.
 *  - Manually entered Admission Numbers are preserved (trimmed & uppercased) and NEVER overwritten.
 *  - Case-insensitive duplicate detection prevents collisions across existing records.
 */

export const ADMISSION_NUMBER_PREFIX = 'STD';

const ADMISSION_NUMBER_PATTERN = /^[A-Z0-9][A-Z0-9/-]{2,31}$/;

/**
 * Normalizes an admission number for canonical storage and case-insensitive comparison.
 */
export function normalizeAdmissionNumber(raw: string | undefined | null): string {
  return (raw ?? '').trim().replace(/\s+/g, '').toUpperCase();
}

/**
 * Validates that a non-empty admission number uses safe alphanumeric / slash / hyphen characters.
 */
export function isValidAdmissionNumber(raw: string | undefined | null): boolean {
  const normalized = normalizeAdmissionNumber(raw);
  if (!normalized) return false;
  return ADMISSION_NUMBER_PATTERN.test(normalized);
}

/**
 * Checks whether `candidate` already exists in `existingAdmissionNos` (case-insensitive).
 */
export function hasDuplicateAdmissionNumber(
  candidate: string,
  existingAdmissionNos: Iterable<string>,
  excludeNormalized?: string
): boolean {
  const target = normalizeAdmissionNumber(candidate);
  if (!target) return false;
  const excluded = excludeNormalized ? normalizeAdmissionNumber(excludeNormalized) : '';
  for (const existing of existingAdmissionNos) {
    const norm = normalizeAdmissionNumber(existing);
    if (!norm) continue;
    if (excluded && norm === excluded) continue;
    if (norm === target) return true;
  }
  return false;
}

/**
 * Generates the next unique admission number in the existing `STD/<YEAR>/<NNNN>` format.
 *
 * Inspects all existing admission numbers for the target year, advances past the highest
 * existing numeric sequence (preserving 4-digit zero-padding such as `0001`, `0002`, or
 * continuing cleanly past existing 4-digit numbers like `1042` -> `1043`), and checks
 * case-insensitively against the full existing set so consecutive registrations never collide.
 */
export function generateNextAdmissionNumber(
  existingAdmissionNos: Iterable<string>,
  year: number = new Date().getFullYear()
): string {
  const normalizedSet = new Set<string>();
  const prefix = `${ADMISSION_NUMBER_PREFIX}/${year}/`;
  const yearPattern = new RegExp(`^${ADMISSION_NUMBER_PREFIX}/${year}/(\\d+)$`, 'i');

  let maxSequence = 0;

  for (const raw of existingAdmissionNos) {
    const norm = normalizeAdmissionNumber(raw);
    if (!norm) continue;
    normalizedSet.add(norm);

    const match = norm.match(yearPattern);
    if (match) {
      const num = parseInt(match[1], 10);
      if (Number.isFinite(num) && num > maxSequence) {
        maxSequence = num;
      }
    }
  }

  let nextSeq = maxSequence + 1;
  while (nextSeq < 1_000_000) {
    const padded = String(nextSeq).padStart(4, '0');
    const candidate = `${prefix}${padded}`;
    if (!normalizedSet.has(candidate)) {
      return candidate;
    }
    nextSeq += 1;
  }

  // Fallback for theoretical sequence exhaustion
  const fallbackSuffix = String(Date.now()).slice(-6);
  return `${prefix}${fallbackSuffix}`;
}

export interface AdmissionNumberResolutionSuccess {
  ok: true;
  admissionNo: string;
  wasAutoGenerated: boolean;
}

export interface AdmissionNumberResolutionFailure {
  ok: false;
  error: string;
}

export type AdmissionNumberResolutionResult =
  | AdmissionNumberResolutionSuccess
  | AdmissionNumberResolutionFailure;

export function isAdmissionNumberFailure(
  result: AdmissionNumberResolutionResult
): result is AdmissionNumberResolutionFailure {
  return result.ok === false;
}

/**
 * Resolves the final student Admission Number during enrollment:
 *  - Empty input -> auto-generates a guaranteed-unique `STD/<YEAR>/<NNNN>`.
 *  - Non-empty input -> validates format and uniqueness, preserving the administrator's
 *    manual entry without ever overwriting it.
 */
export function resolveStudentAdmissionNumber(
  manualInput: string | undefined | null,
  existingAdmissionNos: Iterable<string>,
  options?: { year?: number; excludeNormalized?: string }
): AdmissionNumberResolutionResult {
  const cleaned = normalizeAdmissionNumber(manualInput);

  if (!cleaned) {
    const generated = generateNextAdmissionNumber(existingAdmissionNos, options?.year);
    return {
      ok: true,
      admissionNo: generated,
      wasAutoGenerated: true,
    };
  }

  if (!isValidAdmissionNumber(cleaned)) {
    return {
      ok: false,
      error:
        'Admission Number must be 3–32 characters using only letters, numbers, slashes (/), or hyphens (-), e.g. STD/2026/0001.',
    };
  }

  if (hasDuplicateAdmissionNumber(cleaned, existingAdmissionNos, options?.excludeNormalized)) {
    return {
      ok: false,
      error: `Admission Number "${cleaned}" is already assigned to another student. Enter a unique Admission Number or leave it blank to auto-generate one.`,
    };
  }

  return {
    ok: true,
    admissionNo: cleaned,
    wasAutoGenerated: false,
  };
}
